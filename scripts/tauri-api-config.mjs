// Tauri builds in API mode (VITE_API_ORIGIN): the API origin is build-time configuration, so the http scope and the
// CSP that let the webview reach it are generated here instead of being hard-coded.
//   node scripts/tauri-api-config.mjs   → writes src-tauri/capabilities/api.json and src-tauri/tauri.api.conf.json
// Without VITE_API_ORIGIN both files are removed and the local-first app builds unchanged.
// Only https origins are accepted, plus http://localhost / 127.0.0.1 for `pnpm tauri dev` against the dev stack.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const capabilityFile = path.join(root, "src-tauri/capabilities/api.json");
const configFile = path.join(root, "src-tauri/tauri.api.conf.json");

/** The origin a Tauri build may reach, or null for the local app. Throws on anything else. */
export function apiOrigin(raw) {
  const value = (raw ?? "").trim();
  if (!value) return null;
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`VITE_API_ORIGIN must be an absolute origin for Tauri builds, not "${value}".`);
  }
  const local = url.hostname === "localhost" || url.hostname === "127.0.0.1";
  if (url.protocol !== "https:" && !(url.protocol === "http:" && local)) throw new Error("VITE_API_ORIGIN must use https (http only for localhost).");
  if (url.pathname !== "/" || url.search || url.hash || url.username || url.password) throw new Error("VITE_API_ORIGIN must be an origin only.");
  return url.origin;
}

export function capability(origin) {
  return {
    $schema: "../gen/schemas/desktop-schema.json",
    identifier: "api",
    description:
      "API mode: HTTP access to the platform's API origin only (accounts, listings, photos, runs, events). Generated by scripts/tauri-api-config.mjs; see SECURITY.md.",
    windows: ["main"],
    permissions: [{ identifier: "http:default", allow: [{ url: `${origin}/api/*` }] }],
  };
}

/** The base CSP with the API origin added to connect-src (a merge patch for `tauri --config`). */
export function configPatch(baseConfig, origin) {
  const csp = { ...baseConfig.app.security.csp };
  csp["connect-src"] = `${csp["connect-src"]} ${origin}`;
  return { app: { security: { csp } } };
}

function main() {
  const origin = apiOrigin(process.env.VITE_API_ORIGIN);
  if (!origin) {
    fs.rmSync(capabilityFile, { force: true });
    fs.rmSync(configFile, { force: true });
    console.log("tauri-api-config: local app (VITE_API_ORIGIN unset), no API scope");
    return;
  }
  const base = JSON.parse(fs.readFileSync(path.join(root, "src-tauri/tauri.conf.json"), "utf8"));
  fs.writeFileSync(capabilityFile, `${JSON.stringify(capability(origin), null, 2)}\n`);
  fs.writeFileSync(configFile, `${JSON.stringify(configPatch(base, origin), null, 2)}\n`);
  console.log(`tauri-api-config: API scope and CSP for ${origin}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(`tauri-api-config: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
